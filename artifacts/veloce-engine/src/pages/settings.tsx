import { useEffect } from "react";
import { useAuth } from "@workspace/replit-auth-web";
import { useGetStudioSummary, getGetStudioSummaryQueryKey, useHealthCheck, getHealthCheckQueryKey, useListPlatformAccounts, getListPlatformAccountsQueryKey } from "@workspace/api-client-react";
import { LogIn, LogOut, Server, Cpu, Brain, Upload, Send } from "lucide-react";
import { PageHeader, Pill, Sk, ErrorState, btn } from "@/components/kit";

const CAP_META: Record<string, { label: string; icon: typeof Cpu; on: string; off: string }> = {
  media: { label: "Media processing", icon: Cpu, on: "Real ingest and render jobs can run.", off: "Media jobs unavailable. Demo batches are simulated." },
  ai: { label: "AI scripting", icon: Brain, on: "Hooks and scripts generated by a model.", off: "Scripts use templates. Scores remain heuristic." },
  uploads: { label: "Uploads", icon: Upload, on: "Private uploads up to 500 MB.", off: "Upload storage not configured." },
  publishing: { label: "Direct publishing", icon: Send, on: "Platform publishing available.", off: "Not available. Drafts are planning only." },
};

export default function SettingsPage() {
  useEffect(() => { document.title = "Settings · Veloce Engine"; }, []);
  const { user, isAuthenticated, isLoading, login, logout } = useAuth();
  const summary = useGetStudioSummary({ query: { queryKey: getGetStudioSummaryQueryKey() } });
  const health = useHealthCheck({ query: { queryKey: getHealthCheckQueryKey() } });
  const accounts = useListPlatformAccounts({ query: { queryKey: getListPlatformAccountsQueryKey() } });
  const caps = summary.data?.capabilities;

  return (
    <div className="max-w-3xl">
      <PageHeader eyebrow="06 / Settings" title="Workspace" desc="Account, capability and integration state as reported by the server." />
      <section className="panel p-5 mb-4">
        <div className="label-xs mb-3">Account</div>
        {isLoading ? <Sk className="h-12" /> : isAuthenticated && user ? (
          <div className="flex items-center gap-3 flex-wrap">
            {user.profileImageUrl ? <img src={user.profileImageUrl} alt="" className="w-10 h-10 rounded-md" /> : <div className="w-10 h-10 rounded-md bg-emerald-500/15 border border-emerald-500/25" />}
            <div className="flex-1 min-w-0"><div className="text-[14px]">{[user.firstName, user.lastName].filter(Boolean).join(" ") || "Operator"}</div><div className="mono text-[11.5px] text-zinc-500">{user.email ?? user.id}</div></div>
            <Pill tone="emerald">Signed in</Pill>
            <button className={btn.ghost} onClick={logout} data-testid="button-settings-logout"><LogOut className="w-3.5 h-3.5" /> Log out</button>
          </div>
        ) : (
          <div className="flex items-center gap-3 flex-wrap">
            <div className="flex-1 text-[13px] text-zinc-300">You are browsing the public demo workspace. Demo batches are simulated and clearly labeled. Log in for real media jobs and uploads.</div>
            <button className={btn.primary} onClick={login} data-testid="button-settings-login"><LogIn className="w-3.5 h-3.5" /> Log in</button>
          </div>
        )}
      </section>

      <section className="panel p-5 mb-4">
        <div className="flex items-center justify-between mb-3"><div className="label-xs">Capabilities</div>
          <div className="flex items-center gap-2 mono text-[11px] text-zinc-500"><Server className="w-3 h-3" />{health.isLoading ? "checking" : health.isError ? <span className="text-red-400">API unreachable</span> : <span className="text-emerald-400">API {health.data?.status}</span>}</div></div>
        {summary.isLoading ? <Sk className="h-40" /> : summary.isError ? <ErrorState error={summary.error} onRetry={() => summary.refetch()} /> : caps && (
          <div className="divide-y divide-white/[0.05]">
            {(Object.keys(CAP_META) as (keyof typeof caps)[]).map((k) => { const m = CAP_META[k]; const on = caps[k]; return (
              <div key={k} className="flex items-start gap-3 py-3" data-testid={`row-cap-${k}`}>
                <m.icon className="w-4 h-4 text-zinc-400 mt-0.5" />
                <div className="flex-1"><div className="text-[13px]">{m.label}</div><div className="text-[12px] text-muted-foreground">{on ? m.on : m.off}</div></div>
                <Pill tone={on ? "emerald" : "neutral"}>{on ? "Enabled" : "Off"}</Pill>
              </div>); })}
          </div>)}
      </section>

      <section className="panel p-5">
        <div className="label-xs mb-3">Integrations</div>
        {accounts.isLoading ? <Sk className="h-24" /> : accounts.isError ? <ErrorState error={accounts.error} onRetry={() => accounts.refetch()} /> : (
          <div className="divide-y divide-white/[0.05]">{accounts.data?.map((a) => (
            <div key={a.id} className="flex items-center gap-3 py-2.5"><span className="text-[13px] flex-1">{a.platform}</span><span className="text-[11.5px] text-muted-foreground hidden sm:block">{a.message}</span><Pill tone={a.connected ? "emerald" : "neutral"}>{a.connected ? "Connected" : "Not connected"}</Pill></div>))}</div>)}
      </section>
    </div>
  );
}
